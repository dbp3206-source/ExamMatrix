import http from './httpClient'

const unwrap = (request) => request.then(({ data }) => data)
const authTimeout = 45_000
const googleRequestConfig = { timeout: authTimeout, withCredentials: true }

export const realApi = {
  login: (body) => unwrap(http.post('/auth/login', body, { timeout: authTimeout })),
  refreshSession: () => unwrap(http.post('/auth/refresh', null, { timeout: authTimeout })),
  googleStudentChallenge: () => unwrap(http.post('/auth/google/student/challenge', null, googleRequestConfig)),
  googleStudentLogin: (credential) => unwrap(http.post('/auth/google/student', { credential }, googleRequestConfig)),
  me: () => unwrap(http.get('/auth/me')),
  logout: () => unwrap(http.post('/auth/logout')),
  updateProfile: (body) => unwrap(http.patch('/auth/profile', body)),
  changePassword: (body) => unwrap(http.patch('/auth/password', body)),
  getRoles: () => unwrap(http.get('/roles')),
  getUsers: (params) => unwrap(http.get('/users', { params })),
  getUser: (id) => unwrap(http.get(`/users/${id}`)),
  createUser: (body) => unwrap(http.post('/users', body)),
  updateUser: (id, body) => unwrap(http.patch(`/users/${id}`, body)),
  updateUserStatus: (id, status) => unwrap(http.patch(`/users/${id}/status`, { status })),
  getStudentNameWarnings: (studentId) => unwrap(http.get(`/users/${studentId}/name-warnings`)),
  sendStudentNameWarning: (studentId, body) => unwrap(http.post(`/users/${studentId}/name-warnings`, body)),
  getSubjects: () => unwrap(http.get('/subjects')),
  getSubject: (id) => unwrap(http.get(`/subjects/${id}`)),
  createSubject: (body) => unwrap(http.post('/subjects', body)),
  updateSubject: (id, body) => unwrap(http.patch(`/subjects/${id}`, body)),
  deleteSubject: (id) => unwrap(http.delete(`/subjects/${id}`)),
  getChapters: (params) => unwrap(http.get('/chapters', { params })),
  getChapter: (id) => unwrap(http.get(`/chapters/${id}`)),
  createChapter: (body) => unwrap(http.post('/chapters', body)),
  updateChapter: (id, body) => unwrap(http.patch(`/chapters/${id}`, body)),
  deleteChapter: (id) => unwrap(http.delete(`/chapters/${id}`)),
  getQuestions: (params) => unwrap(http.get('/questions', { params })),
  getQuestion: (id) => unwrap(http.get(`/questions/${id}`)),
  createQuestion: (body) => unwrap(http.post('/questions', body)),
  updateQuestion: (id, body) => unwrap(http.patch(`/questions/${id}`, body)),
  deleteQuestion: (id) => unwrap(http.delete(`/questions/${id}`)),
  getAvailability: (params) => unwrap(http.get('/questions/availability', { params })),
  getMatrices: (params) => unwrap(http.get('/exam-matrices', { params })),
  getMatrix: (id) => unwrap(http.get(`/exam-matrices/${id}`)),
  createMatrix: (body) => unwrap(http.post('/exam-matrices', body)),
  updateMatrix: (id, body) => unwrap(http.patch(`/exam-matrices/${id}`, body)),
  deleteMatrix: (id) => unwrap(http.delete(`/exam-matrices/${id}`)),
  generatePapers: (id, body) => unwrap(http.post(`/exam-matrices/${id}/generate`, body)),
  getGenerationAdvice: (id, body) => unwrap(http.post(`/exam-matrices/${id}/generation-advice`, body)),
  getPapers: (params) => unwrap(http.get('/exam-papers', { params })),
  getPaperSummaries: (params) => unwrap(http.get('/exam-papers/summary', { params })),
  getPaper: (id) => unwrap(http.get(`/exam-papers/${id}`)),
  deletePaper: (id) => unwrap(http.delete(`/exam-papers/${id}`)),
  getDashboard: () => unwrap(http.get('/dashboard/summary')),
  getDashboardAnalytics: (params) => unwrap(http.get('/dashboard/analytics', { params })),
  requestStudentOtp: (body) => unwrap(http.post('/auth/register/student/request-otp', body, { timeout: authTimeout })),
  resendStudentOtp: (body) => unwrap(http.post('/auth/register/student/resend-otp', body, { timeout: authTimeout })),
  registerStudent: (body) => unwrap(http.post('/auth/register/student', body)),
  getMyNameWarnings: () => unwrap(http.get('/student/name-warnings')),
  markMyNameWarningRead: (id) => unwrap(http.patch(`/student/name-warnings/${id}/read`)),
  getTeachers: () => unwrap(http.get('/student/teachers')),
  getStudentClassDiscovery: () => unwrap(http.get('/student/classes/discover')),
  createTeacherRequest: (body) => unwrap(http.post('/student/teacher-requests', body)),
  getCurrentTeacherRequest: () =>
    http.get('/student/teacher-requests/current')
      .then(({ data }) => data)
      .catch((err) => {
        if (err?.status === 404 || err?.response?.status === 404) return null
        throw err
      }),
  getStudentExams: (params) => unwrap(http.get('/student/exams', { params })),
  getStudentExamSubjects: () => unwrap(http.get('/student/exams/subjects')),
  getAdminResultUsers: (params) => unwrap(http.get('/admin/results/users', { params })),
  getAdminTeacherEssays: (teacherId, params) => unwrap(http.get(`/admin/results/teacher/${teacherId}/essays`, { params })),
  getAdminTeacherObjectives: (teacherId, params) => unwrap(http.get(`/admin/results/teacher/${teacherId}/objectives`, { params })),
  getAdminStudentResults: (studentId, params) => unwrap(http.get(`/admin/results/student/${studentId}/attempts`, { params })),
  getStudentExam: (paperId) => unwrap(http.get(`/student/exams/${paperId}`)),
  startExamAttempt: (paperId) => unwrap(http.post(`/student/exams/${paperId}/attempts`)),
  saveAttemptAnswer: (attemptId, body) => unwrap(http.patch(`/student/attempts/${attemptId}/answers`, body)),
  submitExamAttempt: (attemptId) => unwrap(http.post(`/student/attempts/${attemptId}/submit`)),
  getAttemptResult: (attemptId) => unwrap(http.get(`/student/attempts/${attemptId}`)),
  getTeacherStudentRequests: (params) => unwrap(http.get('/teacher/student-requests', { params })),
  reviewStudentRequest: (requestId, body) => unwrap(http.patch(`/teacher/student-requests/${requestId}`, body)),
  approveAllStudentRequests: () => unwrap(http.patch('/teacher/student-requests/approve-all')),
  getPendingGrading: (params) => unwrap(http.get('/teacher/grading/pending', { params })),
  getTeacherResults: (params) => unwrap(http.get('/teacher/results', { params })),
  getGradingAttempt: (attemptId) => unwrap(http.get(`/teacher/grading/attempts/${attemptId}`)),
  gradeAttemptAnswer: (attemptId, attemptAnswerId, body) => unwrap(http.patch(`/teacher/grading/attempts/${attemptId}/answers/${attemptAnswerId}`, body)),
  completeGrading: (attemptId, body) => unwrap(http.patch(`/teacher/grading/attempts/${attemptId}/complete`, body)),
  updatePaperAccess: (id, body) => unwrap(http.patch(`/exam-papers/${id}`, body)),
  getTeacherClass: () => unwrap(http.get('/teacher/classes')),
  updateTeacherClass: (body) => unwrap(http.patch('/teacher/classes', body)),
  previewImportQuestions: (formData) => unwrap(http.post('/questions/import/preview', formData, { headers: { 'Content-Type': 'multipart/form-data' } })),
  confirmImportQuestions: (body) => unwrap(http.post('/questions/import/confirm', body)),
  submitStudentFeedback: (body) => unwrap(http.post('/student/feedbacks', body)),
  getMyFeedbacks: () => unwrap(http.get('/student/feedbacks')),
  getFeedbackInbox: () => unwrap(http.get('/feedbacks/inbox')),
  markFeedbackRead: (id) => unwrap(http.patch(`/feedbacks/${id}/read`)),
  getNotificationSummary: () => unwrap(http.get('/notifications/summary')),
}
